import {
  Array as Arr,
  Console,
  Effect,
  FileSystem,
  Path,
  Record as Rec,
  Schema,
  String as Str,
} from "effect";
import { Command, Flag } from "effect/cli";

import { SetupError } from "../errors.ts";
import { Workspace } from "../services/Workspace.ts";

const toJson = Schema.encodeEffect(Schema.fromJsonString(Schema.Unknown, { space: 2 }));

/** The Markdown files of the skill at `dir`, keyed by their path relative to it, in path order. */
const readSkill = Effect.fn("skills.read")(function* (dir: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;

  const files = yield* fs.readDirectory(dir, { recursive: true });
  const paths = Arr.sort(Arr.filter(files, Str.endsWith(".md")), Str.Order);
  const contents = yield* Effect.forEach(paths, (file) => fs.readFileString(path.join(dir, file)), {
    concurrency: "unbounded",
  });
  return Rec.fromEntries(Arr.zip(paths, contents));
});

/**
 * Embeds the repository's `skills/` in @thenamespace/ens-mcp as a generated module, so the server
 * serves the same files people install from the repository. `--check` fails when it is stale.
 */
export const skillsCommand = Command.make(
  "skills",
  {
    check: Flag.Boolean("check").pipe(
      Flag.withDefault(false),
      Flag.withDescription("Fail if the generated module is out of date, instead of writing it"),
    ),
  },
  ({ check }) =>
    Effect.gen(function* () {
      const workspace = yield* Workspace;
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const skillsDir = path.join(workspace.root, "skills");
      const target = path.join(workspace.root, "packages/ens-mcp/src/skills/files.ts");

      const entries = yield* fs.readDirectory(skillsDir);
      const names = Arr.sort(entries, Str.Order);
      const skills = yield* Effect.forEach(names, (name) => readSkill(path.join(skillsDir, name)), {
        concurrency: "unbounded",
      });
      const json = yield* toJson(Rec.fromEntries(Arr.zip(names, skills)));
      const generated =
        "// Generated by `ens-mcp-dev skills` from the repository's skills/. Do not edit.\n\n" +
        "/** The files of each skill in the repository, keyed by skill name, then path. */\n" +
        `export const skills = ${json};\n`;

      if (!check) return yield* fs.writeFileString(target, generated);
      const current = yield* fs.readFileString(target).pipe(Effect.orElseSucceed(() => ""));
      if (current !== generated)
        return yield* SetupError.make({
          message: "packages/ens-mcp/src/skills/files.ts is out of date: run ens-mcp-dev skills",
        });
      return yield* Console.log("Skills are up to date.");
    }),
).pipe(Command.withDescription("Embed skills/ in the server package"));
